import {randomUUID} from 'node:crypto';
import {existsSync, readFileSync, renameSync, writeFileSync} from 'node:fs';
import {dirname, join, resolve} from 'node:path';
import Ajv from 'ajv';
import standaloneCode from 'ajv/dist/standalone/index.js';
import {buildSync} from 'esbuild';
import definitionSchema from '../packages/web-ui/src/schemas/theme-definition-v1.json';
import manifestSchema from '../packages/web-ui/src/schemas/theme-package-v1.json';

export function generateThemeSchemaValidators(sourceRoot: string): void {
    const ajv = new Ajv({
        allErrors: false,
        strict: true,
        ownProperties: true,
        code: {source: true, esm: true},
    });
    ajv.addSchema(definitionSchema, 'definition');
    ajv.addSchema(manifestSchema, 'manifest');
    const generated = standaloneCode(ajv, {
        validateDefinition: 'definition',
        validateManifest: 'manifest',
    });
    // Bundle Ajv's generated require() calls for runtime helpers into browser-safe ESM.
    const {outputFiles} = buildSync({
        stdin: {contents: generated, resolveDir: resolve(sourceRoot, '../../..')},
        bundle: true,
        format: 'esm',
        platform: 'browser',
        minify: true,
        write: false,
    });
    const output = join(sourceRoot, 'utils', 'themeSchemaValidators.mjs');
    const contents =
        '// Generated by scripts/generate-theme-schema-validators.ts.\n' + outputFiles[0].text;
    if (existsSync(output) && readFileSync(output, 'utf8') === contents) return;

    // Independent Vite and CLI builds may generate this file concurrently.
    const temporary = join(dirname(output), `.themeSchemaValidators-${randomUUID()}.tmp`);
    writeFileSync(temporary, contents);
    renameSync(temporary, output);
}
